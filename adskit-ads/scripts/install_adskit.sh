#!/usr/bin/env bash
# Copies the bundled AdsKit package into an app project and links it to the app target.
#
# usage: install_adskit.sh <App.xcodeproj> [--target NAME] [--dest DIR] [--force]
#   --dest   where the package goes (default: <dir of the .xcodeproj>/Packages/AdsKit)
#   --force  overwrite an existing copy that differs from the bundled one
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd -P)"
src="$here/../assets/AdsKit"

project="" target="" dest="" force=0
while [ $# -gt 0 ]; do
  case "$1" in
    --target) target="$2"; shift 2 ;;
    --dest) dest="$2"; shift 2 ;;
    --force) force=1; shift ;;
    *) project="$1"; shift ;;
  esac
done
[ -n "$project" ] && [ -d "$project" ] || { echo "usage: install_adskit.sh <App.xcodeproj> [--target NAME] [--dest DIR] [--force]" >&2; exit 2; }
project="$(cd "$project" && pwd)"
dest="${dest:-$(dirname "$project")/Packages/AdsKit}"

if [ -f "$(dirname "$project")/project.yml" ]; then
  echo "warning: project.yml found — this project is generated by XcodeGen; add AdsKit to project.yml" \
       "too, or the next \`xcodegen\` run drops the link." >&2
fi

if [ -d "$dest" ]; then
  if diff -rq -x .build -x .swiftpm -x .DS_Store "$src" "$dest" >/dev/null; then
    echo "AdsKit already at $dest (same as bundled copy)"
  elif [ "$force" = 1 ]; then
    rsync -a --delete --exclude .build --exclude .swiftpm --exclude .DS_Store "$src/" "$dest/"
    echo "replaced AdsKit at $dest"
  else
    echo "AdsKit at $dest differs from the bundled copy; keeping it (pass --force to overwrite):" >&2
    diff -rq -x .build -x .swiftpm -x .DS_Store "$src" "$dest" >&2 || true
  fi
else
  mkdir -p "$(dirname "$dest")"
  rsync -a --exclude .build --exclude .swiftpm --exclude .DS_Store "$src/" "$dest/"
  echo "copied AdsKit to $dest"
fi

ruby "$here/link_local_package.rb" "$project" "$dest" ${target:+--target "$target"}
